package com.blogstat.replica;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** 쓰기 쪽 DB와 읽기 쪽 DB를 서로 다른 인메모리 DB로 두고 스냅샷이 왕복하는지 본다. */
class ReplicaRoundTripTest {

    private static final String DDL = "create table search_query_daily("
            + "id bigint generated by default as identity primary key, "
            + "stat_date date not null, search_query varchar(500) not null)";

    @TempDir
    Path dir;

    JdbcTemplate writer;
    JdbcTemplate reader;
    SnapshotPublisher publisher;
    ReplicaLoader loader;
    Path snapshot;

    private static JdbcTemplate memDb() {
        String name = "t_" + UUID.randomUUID().toString().replace("-", "");
        return new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1", "sa", ""));
    }

    @BeforeEach
    void setUp() {
        writer = memDb();
        reader = memDb();
        writer.execute(DDL);
        snapshot = dir.resolve("replica").resolve("snapshot.sql");
        publisher = new SnapshotPublisher(writer, snapshot);
        loader = new ReplicaLoader(reader, snapshot);
    }

    private void insert(String query) {
        writer.update("insert into search_query_daily(stat_date, search_query) values (date '2026-01-02', ?)", query);
    }

    private List<String> readerQueries() {
        return reader.queryForList("select search_query from search_query_daily order by id", String.class);
    }

    /** 같은 크기의 스냅샷이 같은 밀리초에 두 번 만들어져도 바뀐 것으로 보이도록 수정 시각을 확실히 앞으로 민다. */
    private void bumpModified() throws IOException {
        Files.setLastModifiedTime(snapshot, FileTime.from(Instant.now().plusSeconds(5)));
    }

    @Test
    void 쓰기_쪽이_내보낸_스냅샷을_읽기_쪽이_그대로_읽는다() {
        insert("김햄찌 팝업");
        publisher.publish();

        assertTrue(loader.refreshIfChanged());

        assertEquals(List.of("김햄찌 팝업"), readerQueries());
    }

    @Test
    void 따옴표와_특수문자가_든_한글도_깨지지_않는다() {
        String tricky = "김햄찌's \"팝업\" <b>&; -- DROP";
        insert(tricky);
        publisher.publish();

        loader.refreshIfChanged();

        assertEquals(List.of(tricky), readerQueries());
    }

    @Test
    void 스냅샷이_그대로면_다시_올리지_않는다() {
        insert("a");
        publisher.publish();
        assertTrue(loader.refreshIfChanged());

        assertFalse(loader.refreshIfChanged());
    }

    @Test
    void 다시_발행하면_읽기_쪽이_갱신되고_지워진_행은_사라진다() throws IOException {
        insert("지워질 검색어");
        publisher.publish();
        loader.refreshIfChanged();

        writer.update("delete from search_query_daily");
        insert("새 검색어");
        publisher.publish();
        bumpModified();

        assertTrue(loader.refreshIfChanged());
        assertEquals(List.of("새 검색어"), readerQueries());
    }

    @Test
    void 스냅샷이_없으면_아무것도_하지_않고_기존_내용을_유지한다() {
        reader.execute(DDL);
        reader.update("insert into search_query_daily(stat_date, search_query) values (date '2026-01-02', '기존')");

        assertFalse(loader.refreshIfChanged());

        assertEquals(List.of("기존"), readerQueries());
    }

    @Test
    void 읽기_쪽을_바꿔도_쓰기_쪽_원본에는_영향이_없다() {
        insert("원본");
        publisher.publish();
        loader.refreshIfChanged();

        reader.update("delete from search_query_daily");

        assertEquals(1, writer.queryForObject("select count(*) from search_query_daily", Integer.class));
    }

    @Test
    void 발행하면_임시_파일은_남지_않는다() throws IOException {
        insert("a");
        publisher.publish();

        try (var files = Files.list(snapshot.getParent())) {
            assertEquals(List.of("snapshot.sql"), files.map(p -> p.getFileName().toString()).toList());
        }
    }

    @Test
    void 경로에_작은따옴표가_있어도_발행하고_읽는다() {
        Path odd = dir.resolve("it's here").resolve("snapshot.sql");
        SnapshotPublisher oddPublisher = new SnapshotPublisher(writer, odd);
        ReplicaLoader oddLoader = new ReplicaLoader(reader, odd);
        insert("a");

        oddPublisher.publish();

        assertTrue(oddLoader.refreshIfChanged());
        assertEquals(List.of("a"), readerQueries());
    }

    @Test
    void 비밀번호는_스냅샷에_들어가지_않는다() throws IOException {
        writer.execute("create user if not exists secret_user password 'TopSecretPw!' ");
        publisher.publish();

        String text = Files.readString(snapshot);

        assertFalse(text.contains("TopSecretPw!"));
    }
}
