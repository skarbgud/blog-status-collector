package com.blogstat.replica;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.time.Instant;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * 실제 dashboard 프로필로 앱을 띄워, 읽기 전용 복제본으로 동작하는지 본다.
 * 쓰기 쪽 DB는 별도 인메모리 DB로 흉내 내고, 스냅샷 파일만 주고받는다.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("dashboard")
class DashboardReplicaSmokeTest {

    private static final Path DIR;
    private static final Path SNAPSHOT;

    static {
        try {
            DIR = Files.createTempDirectory("replica-smoke");
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        SNAPSHOT = DIR.resolve("snapshot.sql");
    }

    @DynamicPropertySource
    static void props(DynamicPropertyRegistry registry) {
        registry.add("app.replica.file", SNAPSHOT::toString);
    }

    @AfterAll
    static void cleanUp() throws IOException {
        Files.deleteIfExists(SNAPSHOT);
        Files.deleteIfExists(DIR);
    }

    @Autowired
    MockMvc mvc;

    @Value("${spring.datasource.url}")
    String datasourceUrl;

    @Test
    void 대시보드는_파일_DB가_아니라_인메모리_복제본을_연다() {
        // 파일 DB(./data/blogstat)를 열면 쓰기 프로세스와 잠금으로 충돌하고, 원본을 바꿀 수도 있게 된다.
        assertTrue(datasourceUrl.startsWith("jdbc:h2:mem:"), datasourceUrl);
    }

    @Test
    void 스냅샷이_없어도_빈_결과로_응답하고_새_스냅샷을_자동으로_반영한다() throws Exception {
        // 1) 스냅샷이 아직 없다
        mvc.perform(get("/api/dashboard/queries").param("from", "2026-01-02").param("to", "2026-01-02"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.distinctQueries").value(0));

        // 2) 쓰기 쪽이 검색어 2건을 저장하고 스냅샷을 내보낸다
        JdbcTemplate writer = writerDb();
        SnapshotPublisher publisher = new SnapshotPublisher(writer, SNAPSHOT);
        insert(writer, "김햄찌 팝업", 3);
        insert(writer, "부산 햄찌", 1);
        publisher.publish();

        mvc.perform(get("/api/dashboard/queries").param("from", "2026-01-02").param("to", "2026-01-02"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.distinctQueries").value(2))
                .andExpect(jsonPath("$.items[0].query").value("김햄찌 팝업"))
                .andExpect(jsonPath("$.items[0].visits").value(3));

        // 3) 쓰기 쪽이 검색어를 더 저장하고 다시 내보내면, 대시보드 재시작 없이 반영된다
        insert(writer, "세 번째", 1);
        publisher.publish();
        Files.setLastModifiedTime(SNAPSHOT, FileTime.from(Instant.now().plusSeconds(5)));

        mvc.perform(get("/api/dashboard/queries").param("from", "2026-01-02").param("to", "2026-01-02"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.distinctQueries").value(3));
    }

    private static JdbcTemplate writerDb() {
        String name = "w_" + UUID.randomUUID().toString().replace("-", "");
        JdbcTemplate jdbc = new JdbcTemplate(
                new DriverManagerDataSource("jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("create table referrer_daily(id bigint generated by default as identity primary key, "
                + "stat_date date not null, referrer_name varchar(255) not null, visits integer not null, "
                + "ratio double precision not null, search_engine boolean not null, "
                + "collected_at timestamp(6) not null)");
        jdbc.execute("create table search_query_daily(id bigint generated by default as identity primary key, "
                + "stat_date date not null, referrer_name varchar(255) not null, search_query varchar(500) not null, "
                + "visits integer not null, ratio double precision not null, collected_at timestamp(6) not null)");
        return jdbc;
    }

    private static void insert(JdbcTemplate jdbc, String query, int visits) {
        jdbc.update("insert into search_query_daily(stat_date, referrer_name, search_query, visits, ratio, collected_at) "
                + "values (date '2026-01-02', '통합검색', ?, ?, 0, current_timestamp)", query, visits);
    }
}
